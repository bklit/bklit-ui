/**
 * Generates `src/generated/icons.ts`: SVG markup for only the Central icons the
 * monorepo actually uses, in the one style variant `<Icon>` renders.
 *
 * Why: `@central-icons-react/all` ships every icon in every style (2,000+
 * icons x 48 variants) as one string map with no per-icon entry points, so
 * importing it puts ~55 MB raw / ~5.9 MB gzip of JS on every page.
 *
 * Run from the repo root after adding or removing an icon name:
 *   pnpm --filter @bklitui/icons generate
 * Verify the committed file is current (exits 1 if stale):
 *   pnpm --filter @bklitui/icons generate:check
 *
 * A name missing from the generated map is a type error at the usage site
 * (`IconName` is derived from it), so typecheck tells you when to re-run.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const iconsRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(iconsRoot, "../..");
const outFile = join(iconsRoot, "src/generated/icons.ts");

/** The only style `<Icon>` renders. Changing it means re-running this script. */
const ICON_STYLE = {
  join: "round",
  fill: "outlined",
  radius: "0",
  stroke: "1.5",
};

/** Source trees that render `<Icon name=…>` or hold `IconName` values. */
const SCAN_ROOTS = [
  "apps/web",
  "apps/studio-docs",
  "packages/studio/src",
  "packages/ui/src",
];

/** Files that render arbitrary names and use `@bklitui/icons/all` instead. */
const SCAN_EXCLUDE = new Set(["apps/studio-docs/components/icons-catalog.tsx"]);

const SOURCE_EXT = /\.(?:ts|tsx|js|jsx|mjs|md|mdx)$/;
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  ".source",
  ".turbo",
  "dist",
  "out",
  "public",
]);
/** Any quoted `IconPascalCase` literal: `name="IconX"`, `icon: "IconX"`, etc. */
const NAME_LITERAL = /(["'`])(Icon[A-Z][A-Za-z0-9]*)\1/g;

function walk(dir, files) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry)) {
      continue;
    }
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      walk(path, files);
    } else if (SOURCE_EXT.test(entry)) {
      files.push(path);
    }
  }
}

const require = createRequire(join(iconsRoot, "package.json"));
const {
  centralIcons,
  centralIconsMetadata,
} = require("@central-icons-react/all/icons");

const variant = `${ICON_STYLE.join}-${ICON_STYLE.fill}-radius-${ICON_STYLE.radius}-stroke-${ICON_STYLE.stroke}`;

const files = [];
for (const root of SCAN_ROOTS) {
  walk(join(repoRoot, root), files);
}

const used = new Set();
for (const file of files) {
  if (SCAN_EXCLUDE.has(relative(repoRoot, file))) {
    continue;
  }
  for (const match of readFileSync(file, "utf8").matchAll(NAME_LITERAL)) {
    const name = match[2];
    if (centralIconsMetadata[name]) {
      used.add(name);
    }
  }
}

const names = [...used].sort();
const lines = names.map((name) => {
  const svg = centralIcons[`${variant}/${name}`];
  if (!svg) {
    throw new Error(`No "${variant}" markup for ${name}`);
  }
  const title = centralIconsMetadata[name].title;
  return `  ${name}: [${JSON.stringify(title)}, ${JSON.stringify(svg)}],`;
});

const output = `// AUTO-GENERATED by packages/icons/scripts/generate-icons.mjs. Do not edit.
// Re-run \`pnpm --filter @bklitui/icons generate\` after using a new icon name.

/** Style variant baked into \`icons\` below. */
export const iconStyle = ${JSON.stringify(ICON_STYLE)} as const;

/** Icon name -> [accessible title, inner SVG markup] (${names.length} icons). */
export const icons = {
${lines.join("\n")}
} as const satisfies Record<string, readonly [string, string]>;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // Missing file counts as stale.
  }
  if (current !== output) {
    console.error(
      "packages/icons/src/generated/icons.ts is stale. Run `pnpm --filter @bklitui/icons generate`."
    );
    process.exit(1);
  }
  console.log(`icons.ts is up to date (${names.length} icons).`);
} else {
  writeFileSync(outFile, output);
  console.log(
    `Wrote ${relative(repoRoot, outFile)} (${names.length} icons, ${variant}).`
  );
}
